import Foundation
import CryptoKit

/// One pasteboard item: its representations as (UTI type, bytes), in pasteboard order.
public struct PasteboardItemData: Equatable, Sendable {
	public var representations: [(type: String, data: Data)]

	public init(_ representations: [(type: String, data: Data)]) {
		self.representations = representations
	}

	public static func == (a: Self, b: Self) -> Bool {
		a.representations.map(\.type) == b.representations.map(\.type)
			&& a.representations.map(\.data) == b.representations.map(\.data)
	}

	public func data(for type: String) -> Data? { representations.first { $0.type == type }?.data }
}

/// A captured clipboard change, before it is stored.
public struct ClipDraft: Equatable, Sendable {
	public var items: [PasteboardItemData]
	public var sourceBundleID: String?
	public var sourceName: String?
	public var copiedAt: Date

	public init(items: [PasteboardItemData], sourceBundleID: String? = nil, sourceName: String? = nil, copiedAt: Date) {
		self.items = items
		self.sourceBundleID = sourceBundleID
		self.sourceName = sourceName
		self.copiedAt = copiedAt
	}

	public var byteSize: Int { items.reduce(0) { $0 + $1.representations.reduce(0) { $0 + $1.data.count } } }

	/// Dedup identity: SHA-256 over the ordered items. Each item's representations are sorted by type and
	/// every field is length-prefixed, so item boundaries and order are part of the identity.
	public var contentKey: String {
		var hasher = SHA256()
		func put(_ data: Data) {
			var n = UInt64(data.count).bigEndian
			hasher.update(data: Data(bytes: &n, count: 8))
			hasher.update(data: data)
		}
		var count = UInt64(items.count).bigEndian
		hasher.update(data: Data(bytes: &count, count: 8))
		for item in items {
			let sorted = item.representations.sorted { $0.type < $1.type }
			var n = UInt64(sorted.count).bigEndian
			hasher.update(data: Data(bytes: &n, count: 8))
			for rep in sorted {
				put(Data(rep.type.utf8))
				put(rep.data)
			}
		}
		return hasher.finalize().map { String(format: "%02x", $0) }.joined()
	}

	/// A stable UUID derived from the content key, for UI identity.
	public static func uuid(forKey key: String) -> UUID {
		var bytes = [UInt8](repeating: 0, count: 16)
		var index = key.startIndex
		for i in 0..<16 {
			let next = key.index(index, offsetBy: 2)
			bytes[i] = UInt8(key[index..<next], radix: 16) ?? 0
			index = next
		}
		return UUID(uuid: (bytes[0], bytes[1], bytes[2], bytes[3], bytes[4], bytes[5], bytes[6], bytes[7],
			bytes[8], bytes[9], bytes[10], bytes[11], bytes[12], bytes[13], bytes[14], bytes[15]))
	}
}

/// Pasteboard type identifiers Copia reads and writes.
public enum PasteboardTypes {
	public static let string = "public.utf8-plain-text"
	public static let rtf = "public.rtf"
	public static let html = "public.html"
	public static let png = "public.png"
	public static let tiff = "public.tiff"
	public static let fileURL = "public.file-url"
	public static let url = "public.url"
	/// Marks Copia's own writes so capture skips them.
	public static let marker = "app.copia.marker"
	public static let source = "org.nspasteboard.source"

	/// Types Copia stores. Anything else (web archives, dyn.*, OLE) is dropped.
	public static let stored: Set<String> = [string, rtf, html, png, tiff, fileURL, url]

	/// A copy carrying any of these is never captured.
	public static let ignored: Set<String> = [
		"org.nspasteboard.ConcealedType",
		"org.nspasteboard.TransientType",
		"org.nspasteboard.AutoGeneratedType",
		"com.agilebits.onepassword",
		"de.petermaurer.TransientPasteboardType",
		marker,
	]
}
